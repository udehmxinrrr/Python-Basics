#Arithmetic Operators
x = 20
y = 6
print(x + y)
print(x - y)
print(x * y)
print(x / y)
print(x % y) #This is called the Modulus, which is the remainder of the quotient of two numbers

#Comparison Operators
print(x < y)
print(x > y)
print(x <= y)
print(x >= y)
print(x == y)   # == is the symbol for an equal sign in Python
print(x != y) # ! means "not equal to"

#Assignment Operators - these are used to assign or store values in variables
number = 45 #the = is an assignment operator
print(number)
number += 2
print(number)
number -= 2
print(number)

#Logical Operators - They inculde "and" ,"or", "not".
num1 = 67
num2 = 43
print(num1 == num2 and num1 > num2) #an "and" operator only returns a "true" value if all the statements are true
print(num1 == num2 or num1 > num2) #an "or" operator returns a "true" value if any of the statements are true
print(not(num1 == num2 or num1 > num2)) #an "not" operator reverses the result of a statement,eg: if the statement is false, it returns a "true" value












