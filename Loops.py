# 1. While Loop
count = 10 #Assigning a value to a variable in creating loops is called initializing.

while count <= 15:
    print(count)
    count = count + 1

print()

number = 105
while number >= 100:
    print(number)
    number = number - 1

print()

# 2. For Loop
for num in range(20,26,2):# "in" is a membership operator,"range" is a method.
    print(num)

print()

languages = ["Python","Java","C++","Javascript"]
for language in languages:
    print(language)

print()

